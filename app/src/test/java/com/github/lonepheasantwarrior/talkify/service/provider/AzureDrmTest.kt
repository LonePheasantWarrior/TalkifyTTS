    @Test
    fun `matches reference implementation vectors`() {
        for ((timestamp, expected) in vectors) {
            assertEquals("timestamp=$timestamp", expected, AzureDrm.generateSecMsGecV2(timestamp))
        }
    }

    @Test
    fun `token has v2 shape of cs64-sha256 hex pair`() {
        val token = AzureDrm.generateSecMsGecV2(1793000000.0)
        val parts = token.split("-")
        assertEquals(2, parts.size)
        assertEquals(16, parts[0].length)
        assertEquals(64, parts[1].length)
        assertEquals(token, token.uppercase())
    }

    @Test
    fun `timestamps in same five minute window share the token`() {
        // 窗口按 WIN_EPOCH 对齐，故 1793000000 与 1793000001 属同一窗口
        assertEquals(
            AzureDrm.generateSecMsGecV2(1793000000.0),
            AzureDrm.generateSecMsGecV2(1793000001.0)
        )
        // 跨窗口后令牌随之变化
        assertNotEquals(
            AzureDrm.generateSecMsGecV2(1793000001.0),
            AzureDrm.generateSecMsGecV2(1793000299.0)
        )
    }
}
